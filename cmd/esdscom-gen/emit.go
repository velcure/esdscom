package main

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strconv"
	"strings"

	"github.com/velcure/esdscom/internal/xsd"
)

// output renders the model into Go source files, keyed by file name.
func (m *model) output() (map[string][]byte, error) {
	groups := map[string]bool{"": true}
	for _, s := range m.structs {
		groups[s.Group] = true
	}
	for _, s := range m.simples {
		groups[s.Group] = true
	}
	files := map[string][]byte{}
	for g := range groups {
		src, err := m.typesFile(g)
		if err != nil {
			return nil, err
		}
		files[typesFileName(g)] = src
	}
	src, err := m.validateFile()
	if err != nil {
		return nil, err
	}
	files["validate_gen.go"] = src
	return files, nil
}

func typesFileName(group string) string {
	if group == "" {
		return "types_gen.go"
	}
	return "types_" + strings.ToLower(group) + "_gen.go"
}

func (m *model) header(b *bytes.Buffer) {
	fmt.Fprintf(b, "// Code generated by esdscom-gen from %s; DO NOT EDIT.\n\n", m.cfg.Source)
	fmt.Fprintf(b, "package %s\n\n", m.cfg.Package)
}

func gofmt(name string, b *bytes.Buffer) ([]byte, error) {
	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("%s: generated code does not parse: %w", name, err)
	}
	return out, nil
}

func (m *model) typesFile(group string) ([]byte, error) {
	var b bytes.Buffer
	m.header(&b)
	needTime := false
	for _, s := range m.simples {
		if s.Group == group && strings.HasPrefix(s.Accessor, "Time") {
			needTime = true
		}
	}
	if needTime {
		b.WriteString("import \"time\"\n\n")
	}
	if group == "" {
		b.WriteString("// SchemaVersion is the version of the eSDScom schema the types are generated from.\n")
		fmt.Fprintf(&b, "const SchemaVersion = %q\n\n", m.schema.Version)
		b.WriteString("// Namespace is the target namespace of the eSDScom schema.\n")
		fmt.Fprintf(&b, "const Namespace = %q\n\n", m.schema.TargetNamespace)
	}
	for _, s := range m.structs {
		if s.Group == group {
			m.emitStruct(&b, s)
		}
	}
	for _, s := range m.simples {
		if s.Group == group {
			m.emitSimple(&b, s)
		}
	}
	return gofmt(typesFileName(group), &b)
}

func (m *model) emitStruct(b *bytes.Buffer, s *structDef) {
	what := "the XSD complex type " + s.XSDName
	switch {
	case !s.Complex:
		what = "the content model " + s.XSDName
	case strings.Contains(s.XSDName, "/") || s.XSDName == m.cfg.Root:
		what = "the anonymous complex type of element " + s.XSDName
	}
	comment(b, "", joinDoc(s.Doc, s.Name+" corresponds to "+what+"."))
	fmt.Fprintf(b, "type %s struct {\n", s.Name)
	for _, a := range s.Attrs {
		doc := a.Doc
		line := a.Field + " is the attribute " + a.XMLName + "."
		if a.Default != nil {
			line += fmt.Sprintf(" Its schema default is %q.", *a.Default)
		}
		comment(b, "\t", joinDoc(doc, line))
		fmt.Fprintf(b, "\t%s *%s\n", a.Field, a.Ref.GoType)
	}
	if s.Text != nil {
		comment(b, "\t", "Value is the text content.")
		fmt.Fprintf(b, "\tValue %s\n", s.Text.GoType)
	}
	for _, f := range s.Fields {
		comment(b, "\t", f.Doc)
		fmt.Fprintf(b, "\t%s %s\n", f.Name, f.GoType)
	}
	if s.Complex {
		comment(b, "\t", "Extra holds attributes, elements and text the schema does not describe at this place. Encode writes them back.")
		b.WriteString("\tExtra Extra\n")
	}
	b.WriteString("}\n\n")
}

func (m *model) emitSimple(b *bytes.Buffer, s *simpleDef) {
	what := "the XSD simple type " + s.XSDName
	if s.XSDName == "" {
		what = "an anonymous XSD simple type"
	}
	comment(b, "", joinDoc(s.Doc, s.Name+" corresponds to "+what+"."))
	fmt.Fprintf(b, "type %s string\n\n", s.Name)
	if len(s.Enums) > 0 {
		b.WriteString("const (\n")
		for _, e := range s.Enums {
			comment(b, "\t", e.Doc)
			fmt.Fprintf(b, "\t%s %s = %s\n", e.Const, s.Name, strconv.Quote(e.Value))
		}
		b.WriteString(")\n\n")
	}
	fmt.Fprintf(b, "// Valid reports whether v satisfies every constraint of %s.\n", s.Name)
	fmt.Fprintf(b, "func (v %s) Valid() bool { return %s.valid(string(v)) }\n\n", s.Name, s.Desc)
	if s.Accessor != "" {
		method, _, _ := strings.Cut(s.Accessor, "(")
		fn := map[string]string{"Bool": "parseBool", "Int64": "parseInt", "Float64": "parseFloat", "Time": "parseTime"}[method]
		if method == "Float64" && s.Prim == "primDecimal" {
			fn = "parseDecimalFloat"
		}
		if method == "Time" && s.Prim == "primDateTime" {
			fn = "parseDateTime"
		}
		if method == "Time" && s.Prim == "primDate" {
			fn = "parseDate"
		}
		fmt.Fprintf(b, "// %s returns the value of v in its Go representation.\n", method)
		fmt.Fprintf(b, "func (v %s) %s { return %s(string(v)) }\n\n", s.Name, s.Accessor, fn)
	}
}

func (m *model) validateFile() ([]byte, error) {
	var b bytes.Buffer
	m.header(&b)
	b.WriteString("import \"reflect\"\n\n")
	fmt.Fprintf(&b, "const rootName = %q\n\n", m.cfg.Root)

	if len(m.simples) > 0 {
		b.WriteString("var (\n")
	}
	for _, s := range m.simples {
		fmt.Fprintf(&b, "\t%s = &simpleType{name: %q, prim: %s", s.Desc, s.Name, s.Prim)
		if s.Base != "" {
			fmt.Fprintf(&b, ", base: %s", s.Base)
		}
		if len(s.Members) > 0 {
			fmt.Fprintf(&b, ", members: []*simpleType{%s}", strings.Join(s.Members, ", "))
		}
		if len(s.Facets) > 0 {
			fmt.Fprintf(&b, ", facets: []facet{%s}", strings.Join(s.Facets, ", "))
		}
		b.WriteString("}\n")
	}
	if len(m.simples) > 0 {
		b.WriteString(")\n\n")
	}

	var enums []*simpleDef
	for _, s := range m.simples {
		if len(s.Enums) > 0 {
			enums = append(enums, s)
		}
	}
	if len(enums) > 0 {
		b.WriteString("var (\n")
		for _, s := range enums {
			fmt.Fprintf(&b, "\tenum%s = []string{", s.Name)
			for i, e := range s.Enums {
				if i > 0 {
					b.WriteString(", ")
				}
				b.WriteString(strconv.Quote(e.Value))
			}
			b.WriteString("}\n")
		}
		b.WriteString(")\n\n")
	}

	var complexes []*structDef
	for _, s := range m.structs {
		if s.Complex {
			complexes = append(complexes, s)
		}
	}
	sort.SliceStable(complexes, func(i, j int) bool { return complexes[i].Name < complexes[j].Name })
	b.WriteString("var (\n")
	for _, s := range complexes {
		fmt.Fprintf(&b, "\tct%s = &complexType{name: %q}\n", s.Name, s.XSDName)
	}
	fmt.Fprintf(&b, "\trootType = ct%s\n", m.root.Name)
	b.WriteString(")\n\n")

	b.WriteString("func init() {\n")
	for _, s := range complexes {
		fmt.Fprintf(&b, "\tct%s.define(reflect.TypeFor[%s](),\n", s.Name, s.Name)
		if len(s.Attrs) == 0 {
			b.WriteString("\t\tnil,\n")
		} else {
			b.WriteString("\t\t[]attribute{\n")
			for _, a := range s.Attrs {
				fmt.Fprintf(&b, "\t\t\t{name: %q, field: %q, typ: %s},\n", a.XMLName, a.Field, a.Ref.Desc)
			}
			b.WriteString("\t\t},\n")
		}
		if s.Text != nil {
			fmt.Fprintf(&b, "\t\t%s,\n", s.Text.Desc)
		} else {
			b.WriteString("\t\tnil,\n")
		}
		if s.Model == nil {
			b.WriteString("\t\tnil,\n")
		} else {
			b.WriteString("\t\t")
			writeParticle(&b, s.Model, 2)
			b.WriteString(",\n")
		}
		b.WriteString("\t)\n")
	}
	b.WriteString("}\n")
	return gofmt("validate_gen.go", &b)
}

func maxString(n int) string {
	if n == xsd.Unbounded {
		return "unbounded"
	}
	return strconv.Itoa(n)
}

func writeParticle(b *bytes.Buffer, p *particleDef, depth int) {
	switch p.Kind {
	case xsd.ElementParticle:
		switch {
		case p.Any:
			fmt.Fprintf(b, "anyElem(%q, %q, %d, %s)", p.Name, p.Field, p.Min, maxString(p.Max))
		case p.Complex != nil:
			fmt.Fprintf(b, "complexElem(%q, %q, %d, %s, ct%s)", p.Name, p.Field, p.Min, maxString(p.Max), p.Complex.Name)
		default:
			fmt.Fprintf(b, "simpleElem(%q, %q, %d, %s, %s)", p.Name, p.Field, p.Min, maxString(p.Max), p.Simple.Desc)
		}
		return
	case xsd.SequenceParticle:
		fmt.Fprintf(b, "sequence(%q, %d, %s", p.Field, p.Min, maxString(p.Max))
	case xsd.ChoiceParticle:
		fmt.Fprintf(b, "choice(%q, %d, %s", p.Field, p.Min, maxString(p.Max))
	}
	ind := strings.Repeat("\t", depth+1)
	for _, c := range p.Children {
		b.WriteString(",\n" + ind)
		writeParticle(b, c, depth+1)
	}
	b.WriteString(")")
}

// comment writes text as a Go comment, wrapped at 80 columns. Empty text
// writes nothing.
func comment(b *bytes.Buffer, indent, text string) {
	text = strings.TrimSpace(text)
	if text == "" {
		return
	}
	for _, para := range strings.Split(text, "\n") {
		words := strings.Fields(para)
		if len(words) == 0 {
			b.WriteString(indent + "//\n")
			continue
		}
		line := indent + "//"
		for _, w := range words {
			if len(line) > len(indent)+2 && len(line)+1+len(w) > 80 {
				b.WriteString(line + "\n")
				line = indent + "//"
			}
			line += " " + w
		}
		b.WriteString(line + "\n")
	}
}
